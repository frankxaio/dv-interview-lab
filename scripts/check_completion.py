#!/usr/bin/env python3
"""Check the built bank's coverage, solution IDs, and visible author marks.

Run after build_questions.py. Use --require-complete for the final check.
"""
import argparse
from collections import Counter
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--require-complete", action="store_true")
    args = parser.parse_args()
    questions = json.loads((ROOT / "data/questions.json").read_text())
    by_id = {q["id"]: q for q in questions}
    errors = []
    if len(by_id) != len(questions):
        errors.append("duplicate question IDs")
    owners = {}
    for path in sorted((ROOT / "data/solutions").glob("*.json")):
        solutions = json.loads(path.read_text())
        for qid, markdown in solutions.items():
            if qid not in by_id:
                errors.append(f"{path.name}: unknown ID {qid}")
            if qid in owners:
                errors.append(f"{qid}: repeated in {owners[qid]} and {path.name}")
            owners[qid] = path.name
            if path.name.startswith("codex-") and not markdown.startswith("> Completed by Codex."):
                errors.append(f"{qid}: missing Codex attribution")
            if path.name.startswith("gemini-") and not markdown.startswith("> Generated by Gemini via agy."):
                errors.append(f"{qid}: missing Gemini attribution")
            if qid in by_id and by_id[qid]["solution"] != markdown.strip():
                errors.append(f"{qid}: built solution differs; rebuild questions.json")
    missing = [q for q in questions if not q.get("solution", "").strip()]
    authors = Counter()
    for q in questions:
        md = q.get("solution", "")
        if md.startswith("> Completed by Codex."):
            authors["Codex"] += 1
        elif md.startswith("> Generated by Gemini via agy."):
            authors["Gemini via agy"] += 1
        elif md.strip():
            authors["Existing solutions"] += 1
    print(f"Questions: {len(questions)}; solutions: {len(questions) - len(missing)}; missing: {len(missing)}")
    for author, count in sorted(authors.items()):
        print(f"  {author}: {count}")
    for source, count in sorted(Counter(q["source"]["name"] for q in missing).items()):
        print(f"  Missing from {source}: {count}")
    if args.require_complete and missing:
        errors.append("some questions have no illustrated solution")
    for error in errors:
        print("ERROR:", error)
    return bool(errors)


if __name__ == "__main__":
    raise SystemExit(main())
